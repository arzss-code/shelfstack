/**
 * Filter kota berdasarkan provinsi terpilih
 */
export function getCitiesByProvince(provinceId: string): City[] {
  if (!provinceId) return []
  return INDONESIA_CITIES.filter((c) => c.provinceId === String(provinceId))
}

/**
 * Temukan kota berdasarkan ID
 */
export function getCityById(cityId: string): City | undefined {
  if (!cityId) return undefined
  return INDONESIA_CITIES.find((c) => c.id === String(cityId))
}

/**
 * Pencarian cepat fuzzy untuk autocomplete kota, kabupaten, provinsi, atau kode pos
 */
export function searchLocations(query: string, limit: number = 20): City[] {
  const q = (query || '').trim().toLowerCase()
  if (!q || q.length < 2) return []

  const results: City[] = []
  for (const city of INDONESIA_CITIES) {
    if (
      city.name.toLowerCase().includes(q) ||
      city.provinceName.toLowerCase().includes(q) ||
      city.postalCode.includes(q)
    ) {
      results.push(city)
      if (results.length >= limit) break
    }
  }
  return results
}

