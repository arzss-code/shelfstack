-- 1. Create Table
CREATE TABLE public.products (
  id bigint generated by default as identity not null,
  name text not null,
  price numeric not null,
  description text null,
  link text null,
  image_url text null,
  created_at timestamp with time zone null default now(),
  constraint products_pkey primary key (id)
) tablespace pg_default;

-- 2. Tambahkan kolom untuk Soft Delete (Sesuai SOP Talenavi)
ALTER TABLE public.products 
ADD COLUMN deleted_at TIMESTAMP WITH TIME ZONE NULL;

-- 3. Aktifkan Fitur Row Level Security (RLS)
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;

-- 4. Kebijakan Sementara (Bypass)
-- PENTING: Karena belum ada fitur Auth, izinkan akses anonim. 
-- Nanti setelah ada sistem Login, ganti 'true' menjadi '(auth.uid() IS NOT NULL)'
CREATE POLICY "Izinkan semua orang membaca data" 
ON public.products FOR SELECT USING (true);

CREATE POLICY "Izinkan semua orang menambah data" 
ON public.products FOR INSERT WITH CHECK (true);

CREATE POLICY "Izinkan semua orang mengedit data" 
ON public.products FOR UPDATE USING (true);

CREATE POLICY "Izinkan semua orang menghapus data" 
ON public.products FOR DELETE USING (true);
